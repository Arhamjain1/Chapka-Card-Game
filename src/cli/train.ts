/**
 * Trains the generic win table by self-play and writes src/engine/genericTable.ts.
 *
 * Every iteration deals many games in which all three players arrange their hands to
 * maximise expected points against the current table. The strengths they play in each
 * round are then folded into the table, so each iteration answers the play of the
 * iterations before it (fictitious play).
 *
 * Usage: node src/cli/train.ts [--iterations 10] [--deals 4000] [--seed 1]
 */
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { STRENGTH_COUNT, strengthOf, typeOfStrength, SET_TYPES } from '../engine/evaluate.ts';
import { encodeWinTable } from '../engine/model.ts';
import { makeValueTable, optimise, type WinTable } from '../engine/optimiser.ts';
import { ROUNDS, dealCards } from '../engine/rules.ts';
import { mulberry32 } from '../engine/rng.ts';

function argument(name: string, fallback: number): number {
  const index = process.argv.indexOf(`--${name}`);
  return index >= 0 ? Number(process.argv[index + 1]) : fallback;
}

const iterations = argument('iterations', 10);
const deals = argument('deals', 4000);
const rng = mulberry32(argument('seed', 1));

/** Starting point: each opponent set is treated as a random three-card set. */
function seedTable(): WinTable {
  const counts = new Float64Array(STRENGTH_COUNT);
  let total = 0;
  for (let a = 0; a < 52; a++) {
    for (let b = a + 1; b < 52; b++) {
      for (let c = b + 1; c < 52; c++) {
        counts[strengthOf(a, b, c)]++;
        total++;
      }
    }
  }
  const table = new Float32Array(ROUNDS * STRENGTH_COUNT);
  let below = 0;
  for (let s = 0; s < STRENGTH_COUNT; s++) {
    const beatOne = (below + counts[s] / 2) / total;
    below += counts[s];
    for (let round = 0; round < ROUNDS; round++) table[round * STRENGTH_COUNT + s] = beatOne * beatOne;
  }
  return table;
}

/** weighted[round][strength]: how often that strength was the best of a player's two opponents. */
const weighted = new Float64Array(ROUNDS * STRENGTH_COUNT);
let weightTotal = 0;

function tableFromCounts(): WinTable {
  const table = new Float32Array(ROUNDS * STRENGTH_COUNT);
  for (let round = 0; round < ROUNDS; round++) {
    let below = 0;
    for (let s = 0; s < STRENGTH_COUNT; s++) {
      const here = weighted[round * STRENGTH_COUNT + s];
      table[round * STRENGTH_COUNT + s] = (below + here / 2) / weightTotal;
      below += here;
    }
  }
  return table;
}

let table = seedTable();

for (let iteration = 1; iteration <= iterations; iteration++) {
  const value = makeValueTable(table);
  const counts = new Float64Array(ROUNDS * STRENGTH_COUNT);
  const typeCounts = Array.from({ length: ROUNDS }, () => new Map<string, number>());
  const started = performance.now();

  for (let deal = 0; deal < deals; deal++) {
    const { hands, centre, recipient } = dealCards(rng);
    hands[recipient].push(centre);
    const played = hands.map((hand) => optimise(hand, value).strengths);
    for (let round = 0; round < ROUNDS; round++) {
      for (let me = 0; me < 3; me++) {
        const top = Math.max(played[(me + 1) % 3][round], played[(me + 2) % 3][round]);
        counts[round * STRENGTH_COUNT + top]++;
        const type = typeOfStrength(played[me][round]);
        typeCounts[round].set(type, (typeCounts[round].get(type) ?? 0) + 1);
      }
    }
  }

  const perIteration = deals * 3;
  for (let i = 0; i < counts.length; i++) weighted[i] += (iteration * counts[i]) / perIteration;
  weightTotal += iteration;

  const next = tableFromCounts();
  let change = 0;
  for (let i = 0; i < next.length; i++) change = Math.max(change, Math.abs(next[i] - table[i]));
  table = next;

  const seconds = ((performance.now() - started) / 1000).toFixed(1);
  console.log(`iteration ${iteration}/${iterations}: ${seconds}s, largest table change ${change.toFixed(4)}`);
  for (let round = 0; round < ROUNDS; round++) {
    const shares = [...SET_TYPES]
      .reverse()
      .map((type) => `${type} ${(((typeCounts[round].get(type) ?? 0) / perIteration) * 100).toFixed(0)}%`);
    console.log(`  round ${round + 1}: ${shares.join(', ')}`);
  }
}

const target = fileURLToPath(new URL('../engine/genericTable.ts', import.meta.url));
writeFileSync(
  target,
  [
    '/**',
    ' * Generated by `npm run train`. Do not edit by hand.',
    ' * Win chances by round and set strength from self-play, 16-bit little-endian, base64.',
    ' */',
    `export const GENERIC_WIN_BASE64 =\n  '${encodeWinTable(table)}';`,
    '',
  ].join('\n'),
);
console.log(`wrote ${target}`);
